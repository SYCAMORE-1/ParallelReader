/* Local browser QA; uses a bundled Playwright or an installed copy. */
const fs = require('node:fs');
const path = require('node:path');
const modules = process.env.PARALLEL_NODE_MODULES;
const { chromium } = require(modules ? path.join(modules, 'playwright') : 'playwright');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
  const page = await context.newPage();
  const errors = [];
  let alignmentRequests = 0;
  page.on('request', request => { if (request.url().endsWith('/align')) alignmentRequests++; });
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const destination = path.resolve('test-results'); fs.mkdirSync(destination, { recursive: true });
  async function clickSentence(locator) {
    await locator.scrollIntoViewIfNeeded();
    const point = await locator.evaluate(span => {
      const offset = Math.max(0, span.firstChild.textContent.search(/\S/));
      const range = document.createRange(); range.setStart(span.firstChild, offset); range.setEnd(span.firstChild, offset + 1);
      const rect = range.getClientRects()[0]; return { x: rect.x + rect.width / 2, y: rect.y + rect.height / 2 };
    });
    await page.mouse.click(point.x, point.y);
  }
  try {
    await page.goto('http://127.0.0.1:8765', { waitUntil: 'networkidle' });
    await page.locator('#reader').waitFor({ state: 'visible' });
    await page.locator('.translation:not(.placeholder):not(.error)').first().waitFor({ timeout: 60000 });
    const aligned = await page.locator('.paragraph-row').evaluateAll(rows => rows.every(row => Math.abs(row.children[0].getBoundingClientRect().top - row.children[1].getBoundingClientRect().top) < 1));
    if (!aligned) throw Error('Original and translation rows are misaligned');
    await page.screenshot({ path: path.join(destination, 'reader-desktop.png'), fullPage: true });
    const pageNumber = Number(await page.locator('#page-input').inputValue());
    await clickSentence(page.locator('.original .sentence').first());
    await page.locator('.paragraph-row.selected').waitFor();
    await page.locator('#next-page').click();
    if (Number(await page.locator('#page-input').inputValue()) !== pageNumber + 1) throw Error('Next page failed');
    await page.locator('#prev-page').click();
    await page.locator('#model-badge').click();
    await page.locator('#settings-dialog').waitFor({ state: 'visible' });
    await page.locator('#test-model').click();
    await page.waitForFunction(() => document.querySelector('#connection-result').textContent.includes('连接成功'), null, { timeout: 20000 });
    await page.screenshot({ path: path.join(destination, 'settings.png') });
    await page.locator('#settings-dialog .close-dialog').click();
    if (await page.locator('#reading-settings').isVisible()) throw Error('Reading controls must initially be hidden');
    await page.locator('#reader-settings-button').click();
    await page.locator('#reading-settings').waitFor({ state: 'visible' });
    const before = await page.locator('.paragraph-row:not(.heading)').first().evaluate(row => ({ en: getComputedStyle(row.querySelector('.original')).fontSize, zh: getComputedStyle(row.querySelector('.translation')).fontSize }));
    await page.locator('#en-size').focus(); await page.keyboard.press('End');
    const after = await page.locator('.paragraph-row:not(.heading)').first().evaluate(row => ({ en: getComputedStyle(row.querySelector('.original')).fontSize, zh: getComputedStyle(row.querySelector('.translation')).fontSize }));
    if (after.en !== '32px' || after.zh !== before.zh) throw Error('English size must update live and independently');
    await page.locator('#zh-weight').selectOption('700');
    await page.locator('#en-font').selectOption('sans'); await page.locator('#zh-font').selectOption('yahei');
    const typography = await page.locator('.paragraph-row:not(.heading)').first().evaluate(row => ({ enWeight: getComputedStyle(row.querySelector('.original')).fontWeight, zhWeight: getComputedStyle(row.querySelector('.translation')).fontWeight, enFont: getComputedStyle(row.querySelector('.original')).fontFamily, zhFont: getComputedStyle(row.querySelector('.translation')).fontFamily }));
    if (typography.enWeight !== '400' || typography.zhWeight !== '700' || !typography.enFont.includes('Segoe UI') || !typography.zhFont.includes('Microsoft YaHei')) throw Error('Independent fonts or weights failed');
    await page.locator('.theme-choices [data-theme="green"]').click();
    await page.screenshot({ path: path.join(destination, 'reading-settings.png'), fullPage: true });
    await page.reload({ waitUntil: 'networkidle' });
    await page.locator('#reader').waitFor();
    if (!(await page.locator('html').getAttribute('class')).includes('green')) throw Error('Green theme did not persist');
    if (await page.locator('.paragraph-row:not(.heading) .original').first().evaluate(node => getComputedStyle(node).fontSize) !== '32px') throw Error('Independent appearance did not persist');
    await page.locator('#reader-settings-button').click(); await page.locator('#reset-appearance').click();
    await page.locator('#close-reading-settings').click();
    await page.locator('#show-translation').click();
    if (await page.locator('.original').first().isVisible() || !(await page.locator('.translation').first().isVisible())) throw Error('Chinese-only mode failed');
    await page.screenshot({ path: path.join(destination, 'chinese-only.png'), fullPage: true });
    await page.locator('#show-both').click();
    await page.locator('#show-original').click();
    if (await page.locator('.translation').first().isVisible() || !(await page.locator('.original').first().isVisible())) throw Error('English-only mode failed');
    await page.locator('#show-both').click();
    if (await page.locator('.original-label, .translation-label').count()) throw Error('Redundant language captions must be absent');
    await clickSentence(page.locator('.original .sentence').first());
    await page.waitForFunction(() => document.querySelectorAll('.original .sentence-linked').length > 0 && document.querySelectorAll('.translation .sentence-linked').length > 0, null, { timeout: 60000 });
    const rowPid = await page.locator('.paragraph-row.selected').getAttribute('data-pid');
    const translatedSentences = page.locator(`.paragraph-row[data-pid="${rowPid}"] .translation .sentence`);
    const targetIndex = Number(await translatedSentences.last().getAttribute('data-index'));
    await clickSentence(translatedSentences.last());
    await page.waitForFunction(({ pid, targetIndex }) => document.querySelector(`.paragraph-row[data-pid="${pid}"] .translation .sentence-selected`)?.dataset.index === String(targetIndex) && document.querySelector(`.paragraph-row[data-pid="${pid}"] .original .sentence-linked`), { pid: rowPid, targetIndex });
    const libraryResponse = await page.request.get('http://127.0.0.1:8765/api/books'); const library = await libraryResponse.json();
    const bookTitle = await page.locator('#book-title').textContent(); const bookId = library.find(book => book.title === bookTitle).id;
    const statusResponse = await page.request.get(`http://127.0.0.1:8765/api/books/${bookId}/status?page=${pageNumber - 1}`); const status = await statusResponse.json();
    const expectedSource = status.items[rowPid].alignment.find(group => group.target.includes(targetIndex)).source;
    if (status.items[rowPid].alignmentMethod !== 'translation-slots') throw Error('Translation must contain its original sentence mapping');
    const markedSource = await page.locator(`.paragraph-row[data-pid="${rowPid}"] .original .sentence-linked`).evaluateAll(spans => spans.map(span => Number(span.dataset.index)));
    if (JSON.stringify(expectedSource) !== JSON.stringify(markedSource)) throw Error('Highlighted source sentences do not match the semantic alignment');
    const sentenceCounts = await page.locator(`.paragraph-row[data-pid="${rowPid}"]`).evaluate(row => ({ source: row.querySelectorAll('.original .sentence').length, target: row.querySelectorAll('.translation .sentence').length, markedSource: row.querySelectorAll('.original .sentence-linked').length, markedTarget: row.querySelectorAll('.translation .sentence-linked').length }));
    if (sentenceCounts.source > 1 && sentenceCounts.target > 1 && sentenceCounts.markedSource === sentenceCounts.source && sentenceCounts.markedTarget === sentenceCounts.target) throw Error('Sentence selection must not highlight the entire multi-sentence paragraph');
    await page.screenshot({ path: path.join(destination, 'sentence-highlighting.png'), fullPage: true });
    await page.locator('#immersive-button').click();
    await page.waitForFunction(() => document.body.classList.contains('immersive'));
    for (const selector of ['.sidebar', '.topbar', '.book-heading', '.reading-toolbar']) if (await page.locator(selector).isVisible()) throw Error('Immersive mode must hide ' + selector);
    if (!await page.locator('#reading-footer').isVisible()) throw Error('Immersive mode must retain chapter navigation and page progress');
    await page.locator('#show-translation').click();
    if (await page.locator('.original').first().isVisible()) throw Error('Chinese-only mode failed in immersive mode');
    await page.locator('#show-original').click();
    if (await page.locator('.translation').first().isVisible()) throw Error('English-only mode failed in immersive mode');
    await page.locator('#show-both').click();
    await page.locator('#immersive-next').click();
    if (Number(await page.locator('#page-input').inputValue()) !== pageNumber + 1) throw Error('Immersive page navigation failed');
    await page.locator('#immersive-prev').click();
    await page.locator('.translation .sentence').first().waitFor({ timeout: 60000 });
    await clickSentence(page.locator('.translation .sentence').first());
    await page.waitForFunction(() => document.querySelector('.original .sentence-linked') && document.querySelector('.translation .sentence-selected'));
    await page.screenshot({ path: path.join(destination, 'immersive.png'), fullPage: true });
    const sourceSentence = page.locator('.paragraph-row:not(.heading) .original .sentence').first();
    await sourceSentence.scrollIntoViewIfNeeded();
    const hit = await sourceSentence.evaluate(span => {
      const text = span.firstChild.textContent;
      const words = [...text.matchAll(/[A-Za-z]+(?:[’'\-][A-Za-z]+)*/g)];
      const word = words.find(word => word[0].length > 4) || words[0];
      const range = document.createRange(); range.setStart(span.firstChild, word.index); range.setEnd(span.firstChild, word.index + word[0].length);
      const box = range.getClientRects()[0]; return { x: box.x + box.width / 2, y: box.y + box.height / 2, word: word[0] };
    });
    await page.mouse.dblclick(hit.x, hit.y);
    await page.locator('#word-popover').waitFor({ state: 'visible' });
    await page.waitForFunction(() => !document.querySelector('#word-pos').hidden || document.querySelector('#word-popover').classList.contains('word-error'), null, { timeout: 60000 });
    if (await page.locator('#word-pos').isHidden()) throw Error('Word explanation failed: ' + await page.locator('#word-status').textContent());
    if (!await page.locator('#word-basic').textContent() || !await page.locator('#word-meaning').textContent()) throw Error('Both basic and contextual meanings are required');
    await page.screenshot({ path: path.join(destination, 'word-explanation.png') });
    await page.locator('#close-word').click();
    await page.locator('#exit-immersive').click();
    await page.waitForFunction(() => !document.body.classList.contains('immersive'));
    await page.locator('#reader-settings-button').click();
    await page.locator('#prefetch-toggle').click();
    await page.waitForFunction(() => document.querySelector('#prefetch-text').textContent.includes('暂停'));
    await page.locator('#prefetch-toggle').click();
    await page.locator('#close-reading-settings').click();
    await page.locator('#tab-library').click();
    if (await page.locator('.library-book').count() < 1) throw Error('Persistent library missing');
    if (process.env.PARALLEL_TEST_EPUB) {
      const initialCount = await page.locator('.library-book').count();
      await page.locator('#file-input').setInputFiles(process.env.PARALLEL_TEST_EPUB);
      await page.waitForFunction(() => document.querySelector('#toast').textContent.startsWith('已导入'));
      await page.locator('#tab-library').click();
      if (await page.locator('.library-book').count() !== initialCount) throw Error('Importing the same EPUB created a duplicate');
    }
    await page.reload({ waitUntil: 'networkidle' });
    await page.locator('#reader').waitFor({ state: 'visible' });
    if (Number(await page.locator('#page-input').inputValue()) !== pageNumber) throw Error('Reading position not restored');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(destination, 'reader-mobile.png'), fullPage: true });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    if (overflow) throw Error('Mobile layout overflows horizontally');
    await page.locator('#reader-settings-button').click();
    await page.screenshot({ path: path.join(destination, 'settings-mobile.png'), fullPage: true });
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw Error('Mobile settings menu overflows');
    await page.locator('#close-reading-settings').click();
    await page.locator('#sidebar-toggle').click();
    await page.locator('#sidebar').waitFor({ state: 'visible' });
    const welcomePage = await context.newPage();
    await welcomePage.route('**/api/books', route => route.fulfill({ status: 200, contentType: 'application/json', body: '[]' }));
    await welcomePage.setViewportSize({ width: 1440, height: 1000 });
    await welcomePage.goto('http://127.0.0.1:8765', { waitUntil: 'networkidle' });
    await welcomePage.locator('#welcome').waitFor({ state: 'visible' });
    await welcomePage.screenshot({ path: path.join(destination, 'welcome.png'), fullPage: true });
    await welcomePage.close();
    const embeddedPage = await context.newPage();
    await embeddedPage.addInitScript(() => Object.defineProperty(document, 'fullscreenEnabled', { get: () => false }));
    await embeddedPage.goto('http://127.0.0.1:8765', { waitUntil: 'networkidle' });
    await embeddedPage.locator('#immersive-button').click();
    if (!(await embeddedPage.locator('body').getAttribute('class')).includes('immersive')) throw Error('In-app immersive layout must work without native fullscreen');
    await embeddedPage.keyboard.press('Escape');
    await embeddedPage.waitForFunction(() => !document.body.classList.contains('immersive'));
    await embeddedPage.close();
    if (alignmentRequests) throw Error('New translations must not make separate alignment requests: ' + alignmentRequests);
    if (errors.length) throw Error('Browser errors: ' + errors.join('; '));
    console.log(JSON.stringify({ ok: true, selected: true, navigation: true, aligned, modelConnection: true, independentTypography: true, greenTheme: true, explicitColumnButtons: true, immersive: true, inAppFallback: true, bidirectionalSentences: true, separateAlignmentRequests: alignmentRequests, wordExplanation: hit.word, pause: true, fileImport: Boolean(process.env.PARALLEL_TEST_EPUB), positionRestore: true, mobileOverflow: overflow, consoleErrors: errors, screenshots: destination }));
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });

